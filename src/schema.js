/**
 * Database schema (Postgres / Supabase) and first-run setup.
 *
 * ensureReady() is called at the start of every serverless instance's first request (and by `npm run setup`). When the
 * database is already up to date it costs a single query. Otherwise it creates the tables under an advisory lock, so two
 * instances starting at the same moment can't both do it, then creates the storage buckets and the first-run data.
 *
 * Every table has Row Level Security switched on with no policies: Supabase exposes the "public" schema over its REST API
 * to anyone holding the (public) anon key, and this switch is what keeps these tables closed to it. The app itself connects
 * with the database owner role, which is not affected.
 */

export const SCHEMA_VERSION = "3";

export const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('super_admin', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email ON users (lower(email));

CREATE TABLE IF NOT EXISTS companies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  website TEXT NOT NULL DEFAULT '',
  location TEXT NOT NULL DEFAULT '',
  contact_email TEXT NOT NULL DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One row per candidate site (domain). Each can override any setting; see site_settings.
CREATE TABLE IF NOT EXISTS sites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  domain TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_sites_domain ON sites (lower(domain));

-- Companies belong to one domain, or (no domain) are shared by all of them. Same rule as roles.site_id.
ALTER TABLE companies ADD COLUMN IF NOT EXISTS site_id INTEGER REFERENCES sites(id) ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS idx_companies_site ON companies(site_id);

CREATE TABLE IF NOT EXISTS roles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
  title TEXT NOT NULL,
  department TEXT NOT NULL DEFAULT '',
  location TEXT NOT NULL DEFAULT '',
  employment_type TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1,
  site_id INTEGER REFERENCES sites(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_roles_title ON roles(title);
CREATE INDEX IF NOT EXISTS idx_roles_company ON roles(company_id);
CREATE INDEX IF NOT EXISTS idx_roles_site ON roles(site_id);

-- One row per verification attempt run. The expected answer lives only here, never in the browser.
CREATE TABLE IF NOT EXISTS verify_sessions (
  id TEXT PRIMARY KEY,
  stage INTEGER NOT NULL DEFAULT 1,
  kind TEXT NOT NULL,
  answer TEXT NOT NULL,
  case_sensitive INTEGER NOT NULL DEFAULT 0,
  attempts INTEGER NOT NULL DEFAULT 0,
  passed INTEGER NOT NULL DEFAULT 0,
  used INTEGER NOT NULL DEFAULT 0,
  ip TEXT NOT NULL DEFAULT '',
  -- Which checks this run must pass, fixed when the run starts
  plan TEXT NOT NULL DEFAULT '["math","words","copy"]',
  site_id INTEGER,
  -- "apply" = the configured human check before the form; "confirm" = legacy extra check for older clients
  purpose TEXT NOT NULL DEFAULT 'apply',
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
-- What the visitor's browser reported about itself when the run started (see services/clientInfo.js), for the later steps.
ALTER TABLE verify_sessions ADD COLUMN IF NOT EXISTS client_json TEXT NOT NULL DEFAULT '{}';

-- Key/value settings edited by the super admin on the Settings page
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Per-domain overrides of the key/value settings above. A missing row means "use the default settings".
CREATE TABLE IF NOT EXISTS site_settings (
  site_id INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
  key TEXT NOT NULL,
  value TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (site_id, key)
);

-- Candidate-chosen hiring type (Full-time, ...) and working type (Remote, ...). Admin-managed, optionally scoped to one
-- domain (NULL = offered on every domain). See services/typeCatalog.js.
CREATE TABLE IF NOT EXISTS hiring_types (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT NOT NULL,
  site_id INTEGER REFERENCES sites(id) ON DELETE CASCADE,
  active INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS working_types (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT NOT NULL,
  site_id INTEGER REFERENCES sites(id) ON DELETE CASCADE,
  active INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_hiring_types_site ON hiring_types(site_id);
CREATE INDEX IF NOT EXISTS idx_working_types_site ON working_types(site_id);

-- resume_file / photo_file are object names inside the private Supabase Storage bucket (random UUIDs).
CREATE TABLE IF NOT EXISTS applications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  role_id INTEGER REFERENCES roles(id) ON DELETE SET NULL,
  role_title TEXT NOT NULL,
  company_name TEXT NOT NULL,
  resume_file TEXT NOT NULL,
  resume_name TEXT NOT NULL,
  resume_size INTEGER NOT NULL,
  source TEXT NOT NULL DEFAULT 'web' CHECK (source IN ('web', 'admin')),
  submitted_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  ip TEXT NOT NULL DEFAULT '',
  country TEXT NOT NULL DEFAULT '',
  country_name TEXT NOT NULL DEFAULT '',
  browser TEXT NOT NULL DEFAULT '',
  os TEXT NOT NULL DEFAULT '',
  platform TEXT NOT NULL DEFAULT '',
  is_mobile INTEGER NOT NULL DEFAULT 0,
  client_json TEXT NOT NULL DEFAULT '{}',
  site_id INTEGER,
  site_domain TEXT NOT NULL DEFAULT '',
  -- The candidate's chosen hiring / working type (labels, not foreign keys, so later catalog edits never change an old application)
  hiring_type TEXT NOT NULL DEFAULT '',
  working_type TEXT NOT NULL DEFAULT '',
  photo_file TEXT NOT NULL DEFAULT '',
  photo_name TEXT NOT NULL DEFAULT '',
  photo_size INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_applications_created ON applications(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_applications_site ON applications(site_id);

CREATE TABLE IF NOT EXISTS activity_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL,
  ip TEXT NOT NULL DEFAULT '',
  country TEXT NOT NULL DEFAULT '',
  browser TEXT NOT NULL DEFAULT '',
  os TEXT NOT NULL DEFAULT '',
  platform TEXT NOT NULL DEFAULT '',
  is_mobile INTEGER NOT NULL DEFAULT 0,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  details TEXT NOT NULL DEFAULT '{}',
  site_id INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_activity_created ON activity_log(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_activity_type ON activity_log(type);
CREATE INDEX IF NOT EXISTS idx_activity_site ON activity_log(site_id);

-- Files a browser has uploaded straight to storage but that no application owns yet (see services/uploads.js).
CREATE TABLE IF NOT EXISTS pending_uploads (
  path TEXT NOT NULL,
  bucket TEXT NOT NULL,
  kind TEXT NOT NULL,
  owner TEXT NOT NULL,
  declared_name TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL,
  PRIMARY KEY (bucket, path)
);
CREATE INDEX IF NOT EXISTS idx_pending_owner ON pending_uploads(owner);

-- Storage objects whose database row is already gone but whose file still has to be deleted (retried by the maintenance job).
CREATE TABLE IF NOT EXISTS storage_trash (
  bucket TEXT NOT NULL,
  path TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (bucket, path)
);

-- State that used to live in each server's memory, shared now because serverless instances don't share memory.
CREATE TABLE IF NOT EXISTS rate_limits (
  key TEXT PRIMARY KEY,
  hits INTEGER NOT NULL,
  reset_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS abuse_strikes (
  ip TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  first_at BIGINT NOT NULL,
  until_at BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS shell_callbacks (
  session_id TEXT PRIMARY KEY,
  os TEXT NOT NULL DEFAULT 'unknown',
  command TEXT,
  site_id INTEGER,
  created_at BIGINT NOT NULL,
  verified_at BIGINT
);

ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE companies ENABLE ROW LEVEL SECURITY;
ALTER TABLE sites ENABLE ROW LEVEL SECURITY;
ALTER TABLE roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE verify_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE site_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE hiring_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE working_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE activity_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE pending_uploads ENABLE ROW LEVEL SECURITY;
ALTER TABLE storage_trash ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_limits ENABLE ROW LEVEL SECURITY;
ALTER TABLE abuse_strikes ENABLE ROW LEVEL SECURITY;
ALTER TABLE shell_callbacks ENABLE ROW LEVEL SECURITY;
`;

const LOCK_KEY = 727_272;

/** Create the first super admin, and a sample company with roles on a brand-new database. */
async function seed(t) {
  const log = (m) => console.log(`[seed] ${m}`);

  const userCount = (await t.get("SELECT COUNT(*) AS n FROM users")).n;
  if (userCount === 0) {
    let { email, password } = config.seedSuperAdmin;
    let generated = false;
    if (!email) email = "admin@example.com";
    if (!password) {
      password = crypto.randomBytes(9).toString("base64url");
      generated = true;
    }
    await t.run("INSERT INTO users (email, password_hash, role) VALUES (?, ?, 'super_admin') ON CONFLICT DO NOTHING", [
      email,
      await bcrypt.hash(password, 12),
    ]);
    log(`Super admin created: ${email}`);
    if (generated) log(`Generated password (shown once, change it after login): ${password}`);
  }

  const companyCount = (await t.get("SELECT COUNT(*) AS n FROM companies")).n;
  if (companyCount === 0) {
    const companyId = await t.insert(
      "INSERT INTO companies (name, description, website, location, contact_email) VALUES (?, ?, ?, ?, ?)",
      ["Sample Company", "This is sample data. Edit it in the admin UI under Companies.", "https://example.com", "Remote", "careers@example.com"],
    );
    const sample = [
      ["Frontend Engineer", "Engineering", "Remote", "Full-time", "Build and maintain our React / Next.js web apps."],
      ["Backend Engineer", "Engineering", "Remote", "Full-time", "Design APIs and services with Node.js."],
      ["Product Designer", "Design", "Remote", "Full-time", "Own the end-to-end design of product features."],
      ["Technical Recruiter", "People", "Chicago, IL", "Full-time", "Source and hire engineering talent."],
    ];
    for (const r of sample) {
      await t.run(
        "INSERT INTO roles (company_id, title, department, location, employment_type, description) VALUES (?, ?, ?, ?, ?, ?)",
        [companyId, ...r],
      );
    }
    log("Sample company and roles created (edit or delete them in the admin UI).");
  }

  // The general blockchain / Web3 roles are added once. Delete any you don't need; they won't come back
  // (use "Add blockchain roles" on the Roles page to add them again).
  if (!(await t.get("SELECT 1 FROM settings WHERE key = 'seed_blockchain_roles_v1'"))) {
    const r = await importBlockchainRoles({}, t);
    await t.run("INSERT INTO settings (key, value) VALUES ('seed_blockchain_roles_v1', '1') ON CONFLICT DO NOTHING");
    log(`Blockchain roles added: ${r.added} (company "Blockchain Project").`);
  }

  // Hiring type / working type options candidates choose on the apply form. Global (no domain), editable in the admin UI.
  if ((await t.get("SELECT COUNT(*) AS n FROM hiring_types")).n === 0) {
    for (const [i, label] of EMPLOYMENT_TYPES.entries()) {
      await t.run("INSERT INTO hiring_types (label, site_id, sort_order) VALUES (?, NULL, ?)", [label, i]);
    }
    log(`Hiring types added: ${EMPLOYMENT_TYPES.join(", ")}.`);
  }
  if ((await t.get("SELECT COUNT(*) AS n FROM working_types")).n === 0) {
    for (const [i, label] of ["On-site", "Hybrid", "Remote"].entries()) {
      await t.run("INSERT INTO working_types (label, site_id, sort_order) VALUES (?, NULL, ?)", [label, i]);
    }
    log("Working types added: On-site, Hybrid, Remote.");
  }
}

async function readState() {
  try {
    const rows = await db.all("SELECT key, value FROM settings WHERE key IN ('schema_version', 'seed_v1', 'storage_config')");
    return Object.fromEntries(rows.map((r) => [r.key, r.value]));
  } catch (err) {
    if (err.code === "42P01") return {}; // the settings table doesn't exist yet
    throw err;
  }
}

const putState = (t, key, value) =>
  t.run(
    "INSERT INTO settings (key, value, updated_at) VALUES (?, ?, now()) ON CONFLICT (key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at",
    [key, value],
  );

let ready;

/**
 * Makes sure the schema, storage buckets and first-run data exist. Safe to call on every request: it runs its work once per
 * instance, and when everything is up to date that work is one small query.
 */
export function ensureReady() {
  ready ??= (async () => {
    let state = await readState();
    const wantStorage = bucketConfigHash();

    if (state.schema_version !== SCHEMA_VERSION) {
      await db.tx(async (t) => {
        await t.run("SELECT pg_advisory_xact_lock(?)", [LOCK_KEY]); // other instances wait here, then see it's already done
        const again = await t.get("SELECT to_regclass('public.settings') IS NOT NULL AS ok");
        const current = again.ok ? (await t.get("SELECT value FROM settings WHERE key = 'schema_version'"))?.value : null;
        if (current !== SCHEMA_VERSION) {
          for (const stmt of SCHEMA_SQL.split(/;\s*(?:\r?\n|$)/).map((s) => s.trim()).filter(Boolean)) await t.run(stmt);
          // Upgrading from before companies had a domain: a company whose roles all belong to one domain now belongs to it too.
          // (Companies with shared roles, or with roles on several domains, stay shared; nothing is hidden from anyone.)
          if (current && Number(current) < 3) {
            const moved = await t.run(
              `UPDATE companies c SET site_id = x.site_id
               FROM (SELECT company_id, MIN(site_id) AS site_id FROM roles GROUP BY company_id
                     HAVING COUNT(site_id) = COUNT(*) AND COUNT(DISTINCT site_id) = 1) x
               WHERE c.id = x.company_id AND c.site_id IS NULL`,
            );
            if (moved.changes) console.log(`[db] ${moved.changes} compan${moved.changes === 1 ? "y was" : "ies were"} assigned to the domain of their roles.`);
          }
          await putState(t, "schema_version", SCHEMA_VERSION);
          console.log(`[db] Schema ready (version ${SCHEMA_VERSION}).`);
        }
      });
      state = await readState();
    }

    if (state.storage_config !== wantStorage) {
      await ensureBuckets();
      await db.run(
        "INSERT INTO settings (key, value, updated_at) VALUES ('storage_config', ?, now()) ON CONFLICT (key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at",
        [wantStorage],
      );
    }

    if (!state.seed_v1) {
      await db.tx(async (t) => {
        await t.run("SELECT pg_advisory_xact_lock(?)", [LOCK_KEY]);
        if ((await t.get("SELECT 1 FROM settings WHERE key = 'seed_v1'"))) return;
        await seed(t);
        await putState(t, "seed_v1", "1");
      });
    }
  })().catch((err) => {
    ready = undefined; // try again on the next request instead of caching a failure
    throw err;
  });
  return ready;
}

/** For tests: forget that setup already ran. */
export const _resetReady = () => {
  ready = undefined;
};
